def header_module(header: HeaderPlan) -> str:
    """The name of the module of a header."""
    return identifier(snake(header.stem))


def class_module(cls: ClassPlan | StructPlan) -> str:
    """The module that holds the enums that a class or a struct declares."""
    return identifier(snake(cls.model.name))


def build_names(plan: ModulePlan) -> Names:
    classes: dict[str, str] = {}
    enums: dict[str, str] = {}
    structs: dict[str, str] = {}
    enum_plans: dict[str, EnumPlan] = {}
    struct_plans: dict[str, StructPlan] = {}
    errors: list[Diagnostic] = []
    for header in plan.headers:
        prefix = f"crate::{header_module(header)}"
        taken: dict[str, str] = {}
        modules: dict[str, str] = {}

        def claim(
            name: str,
            what: str,
            location: object,
            header: HeaderPlan = header,
            taken: dict[str, str] = taken,
        ) -> None:
            if name in taken:
                errors.append(
                    Diagnostic(
                        f"'{what}' and '{taken[name]}' get the Rust name '{name}' in "
                        f"{header.stem}.h",
                        location,  # type: ignore[arg-type]
                    )
                )
            taken[name] = what

        def nested(
            owner: ClassPlan | StructPlan,
            prefix: str = prefix,
            modules: dict[str, str] = modules,
        ) -> None:
            if not owner.enums:
                return
            module = class_module(owner)
            other = modules.setdefault(module, owner.model.qualified_name)
            if other != owner.model.qualified_name:
                errors.append(
                    Diagnostic(
                        f"'{owner.model.qualified_name}' and '{other}' get the Rust module "
                        f"'{module}' for their enums",
                        owner.model.location,
                    )
                )
            for item in owner.enums:
                enums[item.c_type] = f"{prefix}::{module}::{pascal(item.model.name)}"
                enum_plans[item.model.usr] = item

        for item in header.items:
            if isinstance(item, ClassPlan | EnumPlan | StructPlan):
                claim(pascal(item.model.name), item.model.qualified_name, item.model.location)
            if isinstance(item, ClassPlan):
                classes[item.c_type] = f"{prefix}::{pascal(item.model.name)}"
                nested(item)
            elif isinstance(item, EnumPlan):
                enums[item.c_type] = f"{prefix}::{pascal(item.model.name)}"
                enum_plans[item.model.usr] = item
            elif isinstance(item, StructPlan):
                structs[item.c_type] = f"{prefix}::{pascal(item.model.name)}"
                struct_plans[item.model.usr] = item
                nested(item)
    if errors:
        raise GenerationError(errors)
    return Names(classes, enums, structs, enum_plans, struct_plans)


# native.rs -----------------------------------------------------------------------------------


def native_source(plan: ModulePlan, names: Names) -> str:
    handles = names.types
    src = Source()
    src.line("// Generated by bridgefex. Do not edit.")
    src.line("//! The declarations of the functions of the C API.")
    src.line("#![allow(non_snake_case, dead_code)]")
    src.line()
    src.open('extern "C"')
    src.line(f"pub(crate) fn {plan.last_error}() -> *const ::core::ffi::c_char;")
    src.line(f"pub(crate) fn {plan.api_fingerprint_function}() -> *const ::core::ffi::c_char;")
    src.line(f"pub(crate) fn {plan.free_function}(memory: *mut ::core::ffi::c_void);")
    functions: list[CFunction] = []
    for header in plan.headers:
        functions.extend(header.c_functions)
    for function in functions:
        _declare(src, function, handles)
    src.close()
    return src.text()


def _declare(src: Source, function: CFunction, handles: dict[str, str]) -> None:
    try:
        parameters = ", ".join(
            f"{identifier(param.name)}: {native_type(param, handles)}" for param in function.params
        )
        returns = restype(function, handles)
    except Unsupported as error:
        raise Unsupported(f"'{function.description}': {error}") from error
    src.line(f"pub(crate) fn {function.name}({parameters}){returns};")


# One module per header -----------------------------------------------------------------------


def header_source(plan: ModulePlan, header: HeaderPlan, names: Names) -> str:
    src = Source()
    src.line(f'// Generated by bridgefex from "{header.stem}.h". Do not edit.')
    functions: list[FunctionPlan] = []
    for item in header.items:
        if isinstance(item, ClassPlan):
            src.line()
            _class(src, plan, item, names)
        elif isinstance(item, FunctionPlan):
            functions.append(item)
        elif isinstance(item, EnumPlan):
            src.line()
            _enum(src, item)
        else:
            src.line()
            _struct(src, item, names)
    taken: dict[str, str] = {}
    for item in functions:
        src.line()
        _function(src, plan, item.callable, names, taken, declaring=None, receiver_ok=False)
    return src.text()


def callable_name(call: CallablePlan, constructors: int = 0) -> str:
    """The Rust name of a function, method or constructor: the C++ name in snake case and the
    overload suffix of the C API; a constructor is ``new`` (and its suffix, if the class has
    several)."""
    suffix = snake(call.suffix) if call.suffix else ""
    if call.kind is CallableKind.CONSTRUCTOR:
        return identifier("new" + ("" if constructors == 1 else suffix))
    return identifier(snake(call.name) + suffix)


@dataclass(frozen=True, slots=True)
class Target:
    """Where a function of the C API is in the crate, for what calls the crate by name (the
    runner of the conformance scenarios)."""

    call: CallablePlan
    path: str
    """For a free function, a static method or a constructor: its path from the root of the
    crate; for a method: its name."""

    class_type: str | None = None
    """The C type of the class that the function belongs to."""


def targets(plan: ModulePlan) -> dict[str, Target]:
    """Every function of the C API that the crate wraps, by the name of its C function."""
    found: dict[str, Target] = {}
    for header in plan.headers:
        module = f"{plan.name}::{header_module(header)}"
        for item in header.items:
            if isinstance(item, FunctionPlan):
                call = item.callable
                found[call.function.name] = Target(call, f"{module}::{callable_name(call)}")
            elif isinstance(item, ClassPlan):
                owner = f"{module}::{pascal(item.model.name)}"
                for ctor in item.constructors:
                    name = callable_name(ctor, len(item.constructors))
                    found[ctor.function.name] = Target(ctor, f"{owner}::{name}", item.c_type)
                for member in item.members:
                    name = callable_name(member)
                    static = member.kind is CallableKind.STATIC
                    found[member.function.name] = Target(
                        member, f"{owner}::{name}" if static else name, item.c_type
                    )
    return found


def _class(src: Source, plan: ModulePlan, cls: ClassPlan, names: Names) -> None:
    name = pascal(cls.model.name)
    src.doc(cls.model.qualified_name)
    src.line("#[repr(C)]")
    src.open(f"pub struct {name}")
    src.line("_data: [u8; 0],")
    src.line("_marker: ::core::marker::PhantomData<(*mut u8, ::core::marker::PhantomPinned)>,")
    src.close()
    src.line()
    src.line(f"impl crate::runtime::sealed::Sealed for {name} {{}}")
    src.line()
    src.open(f"impl crate::runtime::Class for {name}")
    src.open(f"unsafe fn destroy(object: *mut {name})")
    src.line(f"unsafe {{ crate::native::{cls.destroy.name}(object) }}")
    src.close()
    src.close()
    src.line()
    src.open(f"impl {name}")
    taken: dict[str, str] = {}
    first = True
    for ctor in cls.constructors:
        if not first:
            src.line()
        first = False
        _function(
            src,
            plan,
            ctor,
            names,
            taken,
            declaring=cls,
            receiver_ok=True,
            called=callable_name(ctor, len(cls.constructors)),
        )
    for member in cls.members:
        if not first:
            src.line()
        first = False
        _function(src, plan, member, names, taken, declaring=cls, receiver_ok=True)
    src.close()
    _inheritance(src, plan, cls, names)
    _nested(src, cls)


def _inheritance(src: Source, plan: ModulePlan, cls: ClassPlan, names: Names) -> None:
    """The class derefs to its first base class (so the methods of the base are its own, and a
    reference to the class goes where a reference to the base is expected); the other bases are
    reached with ``as_<base>``. The pointer to a base is not always the pointer to the object, so
    the conversions are those of the C API."""
    name = pascal(cls.model.name)
    by_view = {view.c_type: view for view in cls.views}
    for position, base in enumerate(cls.bases):
        view = by_view.get(base.c_type)
        if view is None:
            continue
        base_path = names.classes[base.c_type]
        if position == 0:
            src.line()
            src.open(f"impl ::core::ops::Deref for {name}")
            src.line(f"type Target = {base_path};")
            src.line()
            src.open(f"fn deref(&self) -> &{base_path}")
            src.line(f"unsafe {{ &*crate::native::{view.const_upcast.name}(self) }}")
            src.close()
            src.close()
            src.line()
            src.open(f"impl ::core::ops::DerefMut for {name}")
            src.open(f"fn deref_mut(&mut self) -> &mut {base_path}")
            src.line(f"unsafe {{ &mut *crate::native::{view.upcast.name}(self) }}")
            src.close()
            src.close()
        else:
            word = snake(base.model.name)
            src.line()
            src.open(f"impl {name}")
            src.prose(f"This object as a `{base.model.qualified_name}`, which is part of it.")
            src.open(f"pub fn as_{word}(&self) -> &{base_path}")
            src.line(f"unsafe {{ &*crate::native::{view.const_upcast.name}(self) }}")
            src.close()
            src.line()
            src.prose(f"This object as a `{base.model.qualified_name}`, which is part of it.")
            src.open(f"pub fn as_{word}_mut(&mut self) -> &mut {base_path}")
            src.line(f"unsafe {{ &mut *crate::native::{view.upcast.name}(self) }}")
            src.close()
            src.close()
        if base.model.virtual_destructor:
            # C++ destroys the object through the base class: it can be owned as one.
            src.line()
            src.open(f"impl crate::Owned<{name}>")
            src.prose(f"This object, owned as a `{base.model.qualified_name}`.")
            word = "into_base" if position == 0 else f"into_{snake(base.model.name)}"
            src.open(f"pub fn {word}(self) -> crate::Owned<{base_path}>")
            src.line("let object = crate::Owned::into_raw(self);")
            src.line(f"let base = unsafe {{ crate::native::{view.upcast.name}(object) }};")
            src.line(
                'unsafe { crate::Owned::from_raw(base) }.expect("a base of an object is not NULL")'
            )
            src.close()
            src.close()


def _nested(src: Source, owner: ClassPlan | StructPlan) -> None:
    """The enums declared inside a class or a struct, in a module that has its name."""
    if not owner.enums:
        return
    src.line()
    src.prose(f"The enums that `{owner.model.qualified_name}` declares.")
    src.open(f"pub mod {class_module(owner)}")
    for position, enum in enumerate(owner.enums):
        if position:
            src.line()
        _enum(src, enum)
    src.close()


def _enum(src: Source, enum: EnumPlan) -> None:
    """An enum is a type that holds the integer: C++ may give a value that no enumerator has (a
    flag, a value of the range of an enum without a fixed type), which an ``enum`` of Rust cannot
    hold."""
    name = pascal(enum.model.name)
    raw = scalar(enum.model.underlying.c_name)
    src.doc(enum.comment)
    src.line("#[repr(transparent)]")
    src.line("#[derive(Clone, Copy, PartialEq, Eq, Hash)]")
    src.line(f"pub struct {name}(pub {raw});")
    src.line()
    src.open(f"impl {name}")
    constants: dict[str, str] = {}
    for item in enum.enumerators:
        constant = upper_snake(item.model_name)
        if constant in constants:
            raise GenerationError(
                [
                    Diagnostic(
                        f"the enumerators '{constants[constant]}' and '{item.model_name}' of "
                        f"'{enum.model.qualified_name}' get the Rust name '{constant}'",
                        enum.model.location,
                    )
                ]
            )
        constants[constant] = item.model_name
        src.line(f"pub const {constant}: {name} = {name}({item.value});")
    src.close()
    src.line()
    src.open(f"impl ::core::fmt::Debug for {name}")
    src.open("fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result")
    src.open("match self.0")
    seen: set[int] = set()
    for item in enum.enumerators:
        if item.value in seen:
            continue  # an alias: the first enumerator with the value names it
        seen.add(item.value)
        src.line(f'{item.value} => f.write_str("{name}::{upper_snake(item.model_name)}"),')
    src.line(f'other => write!(f, "{name}({{}})", other),')
    src.close()
    src.close()
    src.close()


def _struct(src: Source, struct: StructPlan, names: Names) -> None:
    """A value struct is the mirror of the C struct: it crosses the boundary as it is."""
    name = pascal(struct.model.name)
    src.doc(struct.model.qualified_name)
    src.line("#[repr(C)]")
    src.line("#[derive(Clone, Copy, Debug, PartialEq)]")
    src.open(f"pub struct {name}")
    for member, field_name in zip(struct.fields, field_names(struct), strict=True):
        model = member.model
        type_ = _field_type(model.type, names)
        if model.length is not None:
            type_ = f"[{type_}; {model.length}]"
        src.line(f"pub {field_name}: {type_},")
    src.close()
    src.line()
    src.open(f"impl {name}")
    src.prose(f"The value of a default-constructed `{struct.model.qualified_name}`.")
    src.open("pub fn defaults() -> crate::Result<Self>")
    src.line("crate::runtime::ensure()?;")
    src.line("let mut __result = Self::zeroed();")
    src.line(f"let __status = unsafe {{ crate::native::{struct.init.name}(&mut __result) }};")
    src.line("crate::runtime::check(__status)?;")
    src.line("Ok(__result)")
    src.close()
    src.line()
    src.line("#[allow(dead_code)]")
    src.open("pub(crate) fn zeroed() -> Self")
    src.line("unsafe { ::core::mem::zeroed() }")
    src.close()
    src.close()
    _nested(src, struct)


def field_names(struct: StructPlan) -> list[str]:
    """The Rust names of the members of a struct, in order."""
    taken: set[str] = set()
    names = []
    for member in struct.fields:
        name = unique_name(identifier(snake(member.model.name)), frozenset(taken))
        taken.add(name)
        names.append(name)
    return names


def _field_type(type_: ScalarType | EnumRef | StructRef, names: Names) -> str:
    if isinstance(type_, ScalarType):
        return scalar(type_.c_name)
    if isinstance(type_, EnumRef):
        return names.enums[names.enum_plans[type_.usr].c_type]
    return names.structs[names.struct_plans[type_.usr].c_type]


def _function(
    src: Source,
    plan: ModulePlan,
    call: CallablePlan,
    names: Names,
    taken: dict[str, str],
    *,
    declaring: ClassPlan | None,
    receiver_ok: bool,
    called: str | None = None,
) -> None:
    name = called if called is not None else callable_name(call)
    if name in taken:
        raise GenerationError(
            [
                Diagnostic(
                    f"'{call.function.description}' gets the Rust name '{name}', which "
                    f"'{taken[name]}' has",
                    call.location,
                )
            ]
        )
    taken[name] = call.function.description
    lowered = lower_callable(call, names, plan, declaring=declaring)
    parameters = ([lowered.receiver] if lowered.receiver else []) + lowered.parameters
    src.doc(call.function.description, *lowered.remarks)
    keyword = "pub unsafe fn" if lowered.unsafe else "pub fn"
    head = f"{keyword} {name}{lowered.generics}"
    one = f"{head}({', '.join(parameters)}) -> {lowered.returns} {{"
    if len(one) + 4 <= 100:
        src.open(one.removesuffix(" {"))
    else:
        src.line(f"{head}(")
        for parameter in parameters:
            src.line(f"    {parameter},")
        src.open(f") -> {lowered.returns}")
    src.lines_of(lowered.body)
    src.close()


