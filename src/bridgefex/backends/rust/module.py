def header_module(header: HeaderPlan) -> str:
    """The name of the module of a header."""
    return identifier(snake(header.stem))


def build_names(plan: ModulePlan) -> Names:
    classes: dict[str, str] = {}
    errors: list[Diagnostic] = []
    for header in plan.headers:
        prefix = f"crate::{header_module(header)}"
        taken: dict[str, str] = {}
        for item in header.items:
            if not isinstance(item, ClassPlan | EnumPlan | StructPlan):
                continue
            name = pascal(item.model.name)
            if name in taken:
                errors.append(
                    Diagnostic(
                        f"'{item.model.qualified_name}' and '{taken[name]}' get the Rust name "
                        f"'{name}' in {header.stem}.h",
                        item.model.location,
                    )
                )
            taken[name] = item.model.qualified_name
            if isinstance(item, ClassPlan):
                classes[item.c_type] = f"{prefix}::{name}"
    if errors:
        raise GenerationError(errors)
    return Names(classes)


def refuse_what_is_not_done(plan: ModulePlan) -> None:
    """What the Rust bindings do not have yet is refused first, with the declaration that has
    it (the C functions that it needs would be refused with a worse message)."""
    for header in plan.headers:
        for item in header.items:
            if isinstance(item, EnumPlan | StructPlan):
                kind = "enum" if isinstance(item, EnumPlan) else "struct"
                raise Unsupported(
                    f"the {kind} '{item.model.qualified_name}' is not supported in Rust yet",
                    item.model.location,
                )


# native.rs -----------------------------------------------------------------------------------


def native_source(plan: ModulePlan, names: Names) -> str:
    handles = dict(names.classes)
    src = Source()
    src.line("// Generated by bridgefex. Do not edit.")
    src.line("//! The declarations of the functions of the C API.")
    src.line("#![allow(non_snake_case, dead_code)]")
    src.line()
    src.open('extern "C"')
    src.line(f"pub(crate) fn {plan.last_error}() -> *const ::core::ffi::c_char;")
    src.line(f"pub(crate) fn {plan.api_fingerprint_function}() -> *const ::core::ffi::c_char;")
    src.line(f"pub(crate) fn {plan.free_function}(memory: *mut ::core::ffi::c_void);")
    functions: list[CFunction] = []
    for header in plan.headers:
        functions.extend(header.c_functions)
    for function in functions:
        _declare(src, function, handles)
    src.close()
    return src.text()


def _declare(src: Source, function: CFunction, handles: dict[str, str]) -> None:
    try:
        parameters = ", ".join(
            f"{identifier(param.name)}: {native_type(param, handles)}" for param in function.params
        )
        returns = restype(function.ffi_restype)
    except Unsupported as error:
        raise Unsupported(f"'{function.description}': {error}") from error
    src.line(f"pub(crate) fn {function.name}({parameters}){returns};")


# One module per header -----------------------------------------------------------------------


def header_source(plan: ModulePlan, header: HeaderPlan, names: Names) -> str:
    src = Source()
    src.line(f'// Generated by bridgefex from "{header.stem}.h". Do not edit.')
    functions: list[FunctionPlan] = []
    for item in header.items:
        if isinstance(item, ClassPlan):
            src.line()
            _class(src, plan, item, names)
        elif isinstance(item, FunctionPlan):
            functions.append(item)
        else:
            kind = "enum" if isinstance(item, EnumPlan) else "struct"
            raise Unsupported(
                f"the {kind} '{item.model.qualified_name}' is not supported in Rust yet",
                item.model.location,
            )
    taken: dict[str, str] = {}
    for item in functions:
        src.line()
        _function(src, plan, item.callable, names, taken, declaring=None, receiver_ok=False)
    return src.text()


def callable_name(call: CallablePlan, constructors: int = 0) -> str:
    """The Rust name of a function, method or constructor: the C++ name in snake case and the
    overload suffix of the C API; a constructor is ``new`` (and its suffix, if the class has
    several)."""
    if call.kind is CallableKind.CONSTRUCTOR:
        return identifier("new" + ("" if constructors == 1 else call.suffix))
    return identifier(snake(call.name) + call.suffix)


@dataclass(frozen=True, slots=True)
class Target:
    """Where a function of the C API is in the crate, for what calls the crate by name (the
    runner of the conformance scenarios)."""

    call: CallablePlan
    path: str
    """For a free function, a static method or a constructor: its path from the root of the
    crate; for a method: its name."""

    class_type: str | None = None
    """The C type of the class that the function belongs to."""


def targets(plan: ModulePlan) -> dict[str, Target]:
    """Every function of the C API that the crate wraps, by the name of its C function."""
    found: dict[str, Target] = {}
    for header in plan.headers:
        module = f"{plan.name}::{header_module(header)}"
        for item in header.items:
            if isinstance(item, FunctionPlan):
                call = item.callable
                found[call.function.name] = Target(call, f"{module}::{callable_name(call)}")
            elif isinstance(item, ClassPlan):
                owner = f"{module}::{pascal(item.model.name)}"
                for ctor in item.constructors:
                    name = callable_name(ctor, len(item.constructors))
                    found[ctor.function.name] = Target(ctor, f"{owner}::{name}", item.c_type)
                for member in item.members:
                    name = callable_name(member)
                    static = member.kind is CallableKind.STATIC
                    found[member.function.name] = Target(
                        member, f"{owner}::{name}" if static else name, item.c_type
                    )
    return found


def _class(src: Source, plan: ModulePlan, cls: ClassPlan, names: Names) -> None:
    name = pascal(cls.model.name)
    src.doc(cls.model.qualified_name)
    src.line("#[repr(C)]")
    src.open(f"pub struct {name}")
    src.line("_data: [u8; 0],")
    src.line("_marker: ::core::marker::PhantomData<(*mut u8, ::core::marker::PhantomPinned)>,")
    src.close()
    src.line()
    src.line(f"impl crate::runtime::sealed::Sealed for {name} {{}}")
    src.line()
    src.open(f"impl crate::runtime::Class for {name}")
    src.open(f"unsafe fn destroy(object: *mut {name})")
    src.line(f"unsafe {{ crate::native::{cls.destroy.name}(object) }}")
    src.close()
    src.close()
    src.line()
    src.open(f"impl {name}")
    taken: dict[str, str] = {}
    first = True
    for ctor in cls.constructors:
        if not first:
            src.line()
        first = False
        _function(
            src,
            plan,
            ctor,
            names,
            taken,
            declaring=cls,
            receiver_ok=True,
            called=callable_name(ctor, len(cls.constructors)),
        )
    for member in cls.members:
        if not first:
            src.line()
        first = False
        _function(src, plan, member, names, taken, declaring=cls, receiver_ok=True)
    src.close()


def _function(
    src: Source,
    plan: ModulePlan,
    call: CallablePlan,
    names: Names,
    taken: dict[str, str],
    *,
    declaring: ClassPlan | None,
    receiver_ok: bool,
    called: str | None = None,
) -> None:
    name = called if called is not None else callable_name(call)
    if name in taken:
        raise GenerationError(
            [
                Diagnostic(
                    f"'{call.function.description}' gets the Rust name '{name}', which "
                    f"'{taken[name]}' has",
                    call.location,
                )
            ]
        )
    taken[name] = call.function.description
    lowered = lower_callable(call, names, plan, declaring=declaring)
    parameters = ([lowered.receiver] if lowered.receiver else []) + lowered.parameters
    src.doc(call.function.description, *lowered.remarks)
    one = f"pub fn {name}({', '.join(parameters)}) -> {lowered.returns} {{"
    if len(one) + 4 <= 100:
        src.open(one.removesuffix(" {"))
    else:
        src.line(f"pub fn {name}(")
        for parameter in parameters:
            src.line(f"    {parameter},")
        src.open(f") -> {lowered.returns}")
    src.lines_of(lowered.body)
    src.close()


