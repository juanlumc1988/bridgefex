"""The Rust backend: a crate with ``extern "C"`` declarations and safe wrappers, one module per
header."""

from __future__ import annotations

from pathlib import Path

from ...errors import Diagnostic, GenerationError
from ...plan import ModulePlan
from ...rendering import Renderer
from ..base import Backend
from .check import check
from .mapping import Unsupported
from .module import (
    build_names,
    header_module,
    header_source,
    native_source,
)
from .naming import header_problem, module_problem
from .source import Source

_TEMPLATES = Path(__file__).parent / "templates"

RUST_VERSION = "1.70"
"""The oldest Rust that the generated crate is written for."""


def render(plan: ModulePlan, fingerprint: str) -> dict[str, str]:
    """The crate ``rust/<module>``: the runtime, the declarations of the C functions and a module
    for each header."""
    reasons = [
        f"Rust: {what}: {problem}"
        for what, problem in [
            (f"cannot name the module '{plan.name}'", module_problem(plan.name)),
            *(
                (f"cannot use header name '{header.stem}'", header_problem(header.stem))
                for header in plan.headers
            ),
        ]
        if problem
    ]
    seen: dict[str, str] = {}
    for header in plan.headers:
        word = header_module(header)
        other = seen.setdefault(word, header.stem)
        if other != header.stem:
            reasons.append(
                f"Rust: the headers '{other}.h' and '{header.stem}.h' get the Rust module '{word}'"
            )
    if reasons:
        raise GenerationError([Diagnostic(reason) for reason in reasons])
    names = build_names(plan)
    files: dict[str, str] = {}
    renderer = Renderer(_TEMPLATES, plan, files)
    base = f"rust/{plan.name}"
    env = plan.macro_prefix
    context = {
        "crate": plan.name,
        "rust_version": RUST_VERSION,
        "lib_dir": f"{env}_LIB_DIR",
        "lib_kind": f"{env}_LIB_KIND",
        "fingerprint": fingerprint,
        "last_error": plan.last_error,
        "api_fingerprint": plan.api_fingerprint_function,
        "free": plan.free_function,
    }
    renderer.put(f"{base}/Cargo.toml", "Cargo.toml.j2", **context)
    renderer.put(f"{base}/build.rs", "build.rs.j2", **context)
    renderer.put(f"{base}/src/runtime.rs", "runtime.rs.j2", **context)
    try:
        files[f"{base}/src/native.rs"] = native_source(plan, names)
        for header in plan.headers:
            files[f"{base}/src/{header_module(header)}.rs"] = header_source(plan, header, names)
    except Unsupported as error:
        raise GenerationError([Diagnostic(f"Rust: {error}", error.location)]) from error
    files[f"{base}/src/lib.rs"] = _lib_source(plan)
    return files


def _lib_source(plan: ModulePlan) -> str:
    src = Source()
    src.line("// Generated by bridgefex. Do not edit.")
    src.line(f"//! Bindings of the C++ module `{plan.name}`.")
    src.line()
    src.line("mod native;")
    src.line("mod runtime;")
    for header in plan.headers:
        src.line(f"pub mod {header_module(header)};")
    src.line()
    src.line("pub use runtime::{Class, Error, ErrorKind, Owned, Result};")
    return src.text()


BACKEND = Backend("rust", render, check=check)
