"""The JNI flavor: ``BridgefexNative`` over ``native`` methods, and the C++ glue for them.

Each function of the C API has a Java method with the signature that the FFM flavor gives it (the
code that is generated for the headers is the same), which calls a ``native`` method that takes
the pointers as ``long`` addresses. The glue (``jni/<module>/native/<module>_jni.cpp``) is built
into the same library as the C layer: it registers the native methods when the library is loaded
(``JNI_OnLoad``) and calls the functions of the C API."""

from __future__ import annotations

from ...plan import CFunction, CParam, FfiKind, ModulePlan
from .flavor import JNI
from .lower import Names
from .mapping import Unsupported, native_java
from .source import Source

_JNI_TYPES = {
    "boolean": ("jboolean", "Z"),
    "byte": ("jbyte", "B"),
    "short": ("jshort", "S"),
    "int": ("jint", "I"),
    "long": ("jlong", "J"),
    "float": ("jfloat", "F"),
    "double": ("jdouble", "D"),
    "void": ("void", "V"),
}

_POINTERS = (
    FfiKind.HANDLE,
    FfiKind.VOID_POINTER,
    FfiKind.CHAR_POINTER,
    FfiKind.POINTER,
)


class _Function:
    """A function of the C API as the native layer sees it."""

    def __init__(
        self, name: str, returns: str, params: list[tuple[str, str, str]], pointer: bool
    ) -> None:
        self.name = name
        self.returns = returns
        """The Java type that the wrapper returns (``BridgefexSegment`` for a pointer)."""

        self.params = params
        """(the Java type of the wrapper, the name, the C type) of each parameter."""

        self.pointer_result = pointer
        self.native = f"n_{name}"


def _supported(function: CFunction) -> bool:
    """Whether the glue can call the function (a function pointer is not passed yet)."""
    return not any(
        param.ffi.kind in (FfiKind.CALLBACK, FfiKind.RELEASE) for param in function.params
    )


def _function(function: CFunction) -> _Function:
    try:
        params = [
            (native_java(param.ffi, JNI.segment), f"p_{param.name}", _c_type(param))
            for param in function.params
        ]
        status = function.ffi_restype.kind is FfiKind.STATUS
        returns = "int" if status else native_java(function.ffi_restype, JNI.segment)
    except Unsupported as error:
        raise Unsupported(f"'{function.description}': {error}") from error
    # What counts is the native method, where a pointer is a long.
    slots = sum(
        2 if _java_native_type(type_) in ("long", "double") else 1 for type_, _, _ in params
    )
    if slots > 255:
        raise Unsupported(
            f"'{function.description}' has too many parameters for Java (its C function takes "
            f"{slots} slots of the 255 that a method has: a std::string takes 4)"
        )
    return _Function(function.name, returns, params, function.ffi_restype.kind in _POINTERS)


def _c_type(param: CParam) -> str:
    """The type to cast the address to: a parameter that C declares as an array is a pointer."""
    return f"{param.c_type}*" if param.length is not None else param.c_type


def _functions(plan: ModulePlan) -> list[_Function]:
    functions = [
        _Function(plan.last_error, JNI.segment, [], True),
        _Function(plan.api_fingerprint_function, JNI.segment, [], True),
        _Function(plan.free_function, "void", [(JNI.segment, "p_memory", "void*")], False),
    ]
    for header in plan.headers:
        functions.extend(_function(f) for f in header.c_functions if _supported(f))
    return functions


def _java_native_type(java: str) -> str:
    return "long" if java == JNI.segment else java


def native_source(plan: ModulePlan, names: Names) -> str:
    """``BridgefexNative`` (Java): a static method for each function of the C API."""
    functions = _functions(plan)
    src = Source()
    src.line("// Generated by bridgefex. Do not edit.")
    src.line(f"package {names.root};")
    src.line()
    src.doc("The functions of the C API, for the generated code. It is not part of the API.")
    src.open("public final class BridgefexNative")
    src.open("private BridgefexNative()")
    src.close()
    src.line()
    src.doc("The message of the last error of this thread.")
    src.open(f"static {JNI.segment} lastError()")
    src.line(f"return {plan.last_error}();")
    src.close()
    src.line()
    src.doc(
        "What the runtime needs of the glue: the address of a direct buffer, the length of a C "
        "string, a copy."
    )
    for declaration in (
        "static native long addressOf(java.nio.ByteBuffer buffer);",
        "static native int length(long address);",
        "static native byte[] copyOut(long address, int size);",
        "static native long sizes();",
    ):
        src.line(declaration)
    for function in functions:
        src.line()
        parameters = ", ".join(f"{type_} {name}" for type_, name, _ in function.params)
        src.open(f"public static {function.returns} {function.name}({parameters})")
        src.line("BridgefexRuntime.ensureLoaded();")
        arguments = ", ".join(
            f"{name}.address()" if type_ == JNI.segment else name
            for type_, name, _ in function.params
        )
        call = f"{function.native}({arguments})"
        if function.returns == "void":
            src.line(f"{call};")
        elif function.pointer_result:
            src.line(f"return {JNI.segment}.ofAddress({call});")
        else:
            src.line(f"return {call};")
        src.close()
        native_parameters = ", ".join(
            f"{_java_native_type(type_)} {name}" for type_, name, _ in function.params
        )
        native_returns = "long" if function.pointer_result else function.returns
        src.line(f"private static native {native_returns} {function.native}({native_parameters});")
    src.close()
    return src.text()


def _descriptor(function: _Function) -> str:
    letters = "".join(_JNI_TYPES[_java_native_type(type_)][1] for type_, _, _ in function.params)
    result = "long" if function.pointer_result else function.returns
    return f"({letters}){_JNI_TYPES[result][1]}"


def glue_parts(plan: ModulePlan) -> dict[str, object]:
    """What the template of the glue needs: the includes, a C++ function for each function of the
    C API and the entry of each in the table of native methods."""
    functions = _functions(plan)
    methods = [
        f'{{const_cast<char*>("{function.native}"), const_cast<char*>("{_descriptor(function)}"), '
        f"reinterpret_cast<void*>(glue_{function.name})}},"
        for function in functions
    ]
    return {
        "headers": list(plan.public_headers),
        "functions": ["\n".join(_glue_function(function)) for function in functions],
        "methods": methods,
        "module": plan.name,
        "macro": plan.macro_prefix,
    }


def _glue_function(function: _Function) -> list[str]:
    parameters = ["JNIEnv* env", "jclass cls"]
    arguments: list[str] = []
    for position, (type_, _name, c_type) in enumerate(function.params):
        jni = "jlong" if type_ == JNI.segment else _JNI_TYPES[type_][0]
        parameters.append(f"{jni} a{position}")
        if type_ == JNI.segment:
            arguments.append(f"({c_type}) static_cast<uintptr_t>(a{position})")
        else:
            arguments.append(f"({c_type}) a{position}")
    call = f"{function.name}({', '.join(arguments)})"
    returns = "jlong" if function.pointer_result else _JNI_TYPES[function.returns][0]
    lines = [
        f"{returns} JNICALL glue_{function.name}({', '.join(parameters)})",
        "{",
        "    (void) env;",
        "    (void) cls;",
    ]
    if function.pointer_result:
        lines.append(f"    return static_cast<jlong>(reinterpret_cast<uintptr_t>({call}));")
    elif function.returns == "void":
        lines.append(f"    {call};")
    else:
        lines.append(f"    return static_cast<{returns}>({call});")
    lines.append("}")
    return lines


__all__ = ["glue_parts", "native_source"]
