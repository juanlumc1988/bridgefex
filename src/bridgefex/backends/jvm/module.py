JAVA_LANG = "java.lang"


def header_package(plan: ModulePlan, header: HeaderPlan) -> str:
    return f"{package_word(plan.name)}.{package_word(header.stem)}"


# The native declarations ------------------------------------------------------------------

_Declaration = tuple[str, str, list[tuple[str, str, str]]]
"""(the name of the C function, the Java type it returns, its parameters as (Java type, name,
layout))."""


def native_source(plan: ModulePlan, names: Names) -> str:
    """``BridgefexNative``: a static method for each function of the C API, over a downcall
    handle. The handles are in a class of their own, which is initialised (and so bound to the
    library) only after the library was loaded: a failure to load it can be tried again."""
    declarations: list[_Declaration] = [
        (plan.last_error, SEGMENT, []),
        (plan.api_fingerprint_function, SEGMENT, []),
        (plan.free_function, "void", [(SEGMENT, "p_memory", "BridgefexRuntime.ADDRESS")]),
    ]
    for header in plan.headers:
        declarations.extend(_declaration(function) for function in header.c_functions)
    src = Source()
    src.line("// Generated by bridgefex. Do not edit.")
    src.line(f"package {names.root};")
    src.line()
    for imported in (
        "java.lang.foreign.FunctionDescriptor",
        "java.lang.foreign.MemorySegment",
        "java.lang.invoke.MethodHandle",
        "java.lang.invoke.MethodType",
    ):
        src.line(f"import {imported};")
    src.line()
    src.doc("The functions of the C API, for the generated code. It is not part of the API.")
    src.open("public final class BridgefexNative")
    src.open("private BridgefexNative()")
    src.close()
    src.line()
    src.doc("The message of the last error of this thread.")
    src.open(f"static {SEGMENT} lastError()")
    src.line(f"return {plan.last_error}();")
    src.close()
    handles = Source()
    for declaration in declarations:
        src.line()
        _method(src, declaration)
        _handle(handles, declaration)
    src.line()
    src.open("private static final class Handles")
    src.lines_of(handles.lines)
    src.close()
    src.close()
    return src.text()


def _method(src: Source, declaration: _Declaration) -> None:
    name, returns, params = declaration
    parameters = ", ".join(f"{type_} {pname}" for type_, pname, _ in params)
    arguments = ", ".join(pname for _, pname, _ in params)
    src.open(f"public static {returns} {name}({parameters})")
    src.open("try")
    src.line("BridgefexRuntime.ensureLoaded();")
    call = f"Handles.{name}.invokeExact({arguments})"
    src.line(f"return ({returns}) {call};" if returns != "void" else f"{call};")
    src.close()
    src.open("catch (Throwable error)")
    src.line("throw BridgefexRuntime.unchecked(error);")
    src.close()
    src.close()


def _handle(src: Source, declaration: _Declaration) -> None:
    name, returns, params = declaration
    layouts = [layout for _, _, layout in params]
    classes = [f"{type_}.class" for type_, _, _ in params]
    if returns == "void":
        descriptor = f"FunctionDescriptor.ofVoid({', '.join(layouts)})"
    else:
        result = "BridgefexRuntime.ADDRESS" if returns == SEGMENT else "BridgefexRuntime.C_INT"
        descriptor = f"FunctionDescriptor.of({', '.join([result, *layouts])})"
    method_type = f"MethodType.methodType({', '.join([f'{returns}.class', *classes])})"
    src.line(f"static final MethodHandle {name} = BridgefexRuntime.bind(")
    src.line(f'    "{name}", {descriptor}, {method_type});')


def _declaration(function: CFunction) -> _Declaration:
    try:
        params = [
            (native_java(param.ffi), f"p_{param.name}", native_layout(param.ffi))
            for param in function.params
        ]
        status = function.ffi_restype.kind is FfiKind.STATUS
        returns = "int" if status else native_java(function.ffi_restype)
    except Unsupported as error:
        raise Unsupported(f"'{function.description}': {error}") from error
    return function.name, returns, params


# One package for each header ----------------------------------------------------------------


def functions_source(
    plan: ModulePlan, header: HeaderPlan, functions: list[FunctionPlan], names: Names
) -> str:
    src = Source()
    src.line(f'// Generated by bridgefex from "{header.stem}.h". Do not edit.')
    src.line(f"package {header_package(plan, header)};")
    src.line()
    for imported in (
        "BridgefexFunction",
        "BridgefexNative",
        "BridgefexRuntime",
        "BridgefexUnsigned",
    ):
        src.line(f"import {names.root}.{imported};")
    src.line()
    src.doc(f"The functions of {header.stem}.h.")
    src.open("public final class Functions")
    src.line("private Functions() {")
    src.line("}")
    taken: dict[str, str] = {}
    reserved = RESERVED_MEMBERS | {"Functions"}
    for item in functions:
        call = item.callable
        name = method_name(call.name + call.suffix, reserved)
        if name in taken:
            raise GenerationError(
                [
                    Diagnostic(
                        f"'{call.function.description}' gets the Java name '{name}', which "
                        f"'{taken[name]}' has",
                        call.location,
                    )
                ]
            )
        taken[name] = call.function.description
        lowered = lower_callable(call, names, plan)
        src.line()
        src.doc(call.function.description, *lowered.remarks)
        src.line(f'@BridgefexFunction("{call.function.name}")')
        src.lines_of(lowered.annotations)
        src.open(f"public static {lowered.returns} {name}({', '.join(lowered.parameters)})")
        src.lines_of(lowered.body)
        src.close()
    src.close()
    return src.text()


# Names ---------------------------------------------------------------------------------------


def build_names(plan: ModulePlan) -> Names:
    """The Java name of every class, enum and struct of the module."""
    root = package_word(plan.name)
    enums: dict[str, str] = {}
    structs: dict[str, str] = {}
    classes: dict[str, str] = {}
    enum_plans: dict[str, EnumPlan] = {}
    struct_plans: dict[str, StructPlan] = {}
    errors: list[Diagnostic] = []
    for header in plan.headers:
        package = header_package(plan, header)
        taken: dict[str, str] = {"functions": "the functions of the header"}

        def claim(
            name: str,
            what: str,
            taken: dict[str, str] = taken,
            header: HeaderPlan = header,
        ) -> None:
            if name in RUNTIME_TYPES:
                errors.append(
                    Diagnostic(
                        f"'{what}' gets the Java name '{name}', which the runtime of the "
                        "bindings uses"
                    )
                )
            other = taken.setdefault(name.casefold(), what)
            if other != what:
                errors.append(
                    Diagnostic(
                        f"'{what}' and '{other}' get the Java name '{name}' in "
                        f"{header.stem}.h (files that differ only by case are one on some systems)"
                    )
                )

        for item in header.items:
            if isinstance(item, ClassPlan):
                name = pascal(item.model.name)
                claim(name, item.model.qualified_name)
                classes[item.c_type] = f"{package}.{name}"
                for nested in item.enums:
                    enums[nested.c_type] = f"{package}.{name}.{pascal(nested.model.name)}"
                    enum_plans[nested.model.usr] = nested
            elif isinstance(item, EnumPlan):
                name = pascal(item.model.name)
                claim(name, item.model.qualified_name)
                enums[item.c_type] = f"{package}.{name}"
                enum_plans[item.model.usr] = item
            elif isinstance(item, StructPlan):
                name = pascal(item.model.name)
                claim(name, item.model.qualified_name)
                structs[item.c_type] = f"{package}.{name}"
                struct_plans[item.model.usr] = item
                for nested in item.enums:
                    enums[nested.c_type] = f"{package}.{name}.{pascal(nested.model.name)}"
                    enum_plans[nested.model.usr] = nested
    if errors:
        raise GenerationError(errors)
    return Names(root, enums, structs, classes, enum_plans, struct_plans)


# One file for each class, enum and struct of a header -----------------------------------------


def type_source(
    plan: ModulePlan,
    header: HeaderPlan,
    item: EnumPlan | StructPlan,
    names: Names,
) -> str:
    """The file of an enum or a struct: its own class, in the package of the header."""
    src = Source()
    src.line(f'// Generated by bridgefex from "{header.stem}.h". Do not edit.')
    src.line(f"package {header_package(plan, header)};")
    src.line()
    for imported in (
        "BridgefexNative",
        "BridgefexRuntime",
        "BridgefexUnsigned",
    ):
        src.line(f"import {names.root}.{imported};")
    src.line()
    if isinstance(item, EnumPlan):
        enum_class(src, item, nested=False)
    else:
        struct_class(src, item, names)
    return src.text()
