ENV_REQUIRED = "BRIDGEFEX_REQUIRE_RUST"
"""Set by the CI: a missing cargo is then a failure of the tests that need it, not a skip."""


def available() -> bool:
    return cargo() is not None


def skip_without_rust() -> None:
    """Skip the test if cargo is missing, or fail it if the environment requires it."""
    if available():
        return
    if os.environ.get(ENV_REQUIRED) == "1":
        pytest.fail(f"cargo is required ({ENV_REQUIRED} is set) and it is not installed")
    pytest.skip("needs cargo")


_CARGO = """\
[package]
name = "{name}"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
{crate} = {{ path = "{path}" }}

[workspace]
"""

_PRELUDE = """\
// Generated by tests/conformance/runner_rust.py.
#![allow(dead_code, unreachable_code, unused_mut, unused_parens, unused_variables, unused_imports)]

type Failure = (usize, String);

fn ok<T>(step: usize, result: {crate}::Result<T>) -> Result<T, Failure> {{
    result.map_err(|error| {{
        (step, format!("unexpected {{:?}}: {{}}", error.kind(), error.message()))
    }})
}}

fn fails<T>(
    step: usize,
    result: {crate}::Result<T>,
    kind: {crate}::ErrorKind,
    message: Option<&str>,
) -> Result<(), Failure> {{
    match result {{
        Ok(_) => Err((step, format!("expected {{:?}}, and the call succeeded", kind))),
        Err(error) => {{
            if error.kind() != kind {{
                return Err((step, format!("expected {{:?}}, got {{:?}}", kind, error.kind())));
            }}
            match message {{
                Some(text) if !error.message().contains(text) => Err((
                    step,
                    format!("the message {{:?}} does not contain {{:?}}", error.message(), text),
                )),
                _ => Ok(()),
            }}
        }}
    }}
}}
"""

_FLOAT_MAX = 3.4028234663852886e38

_KINDS = {
    "exception": "Exception",
    "unknown_exception": "UnknownException",
    "out_of_memory": "OutOfMemory",
}


def _integer_range(type_: ScalarType) -> tuple[int, int] | None:
    """The values that a C integer type holds on this machine (the runner runs where the library
    was built), or None for a type that is not an integer."""
    if type_.category not in (TypeCategory.SIGNED_INTEGER, TypeCategory.UNSIGNED_INTEGER):
        return None
    name = type_.c_name
    c_types = {
        "signed char": ctypes.c_byte,
        "unsigned char": ctypes.c_ubyte,
        "short": ctypes.c_short,
        "unsigned short": ctypes.c_ushort,
        "int": ctypes.c_int,
        "unsigned int": ctypes.c_uint,
        "long": ctypes.c_long,
        "unsigned long": ctypes.c_ulong,
        "long long": ctypes.c_longlong,
        "unsigned long long": ctypes.c_ulonglong,
        "int8_t": ctypes.c_int8,
        "uint8_t": ctypes.c_uint8,
        "int16_t": ctypes.c_int16,
        "uint16_t": ctypes.c_uint16,
        "int32_t": ctypes.c_int32,
        "uint32_t": ctypes.c_uint32,
        "int64_t": ctypes.c_int64,
        "uint64_t": ctypes.c_uint64,
        "size_t": ctypes.c_size_t,
    }
    bits = ctypes.sizeof(c_types[name]) * 8
    unsigned = name.startswith("unsigned") or name.startswith("uint") or name == "size_t"
    return (0, 2**bits - 1) if unsigned else (-(2 ** (bits - 1)), 2 ** (bits - 1) - 1)


def _integer(value: object) -> int | None:
    if isinstance(value, dict) and set(value) == {"int"}:
        return int(str(value["int"]))
    if isinstance(value, int) and not isinstance(value, bool):
        return value
    return None


def _float(value: object, bits: int) -> str:
    """A floating-point literal of ``bits`` bits."""
    suffix = f"f{bits}"
    number = float(value)  # type: ignore[arg-type]
    if math.isnan(number):
        return f"{suffix}::NAN"
    if math.isinf(number):
        return f"{suffix}::INFINITY" if number > 0 else f"{suffix}::NEG_INFINITY"
    return f"{number!r}_{suffix}"


class _Unplayable(Exception):
    """A value that the scenario gives and the Rust program cannot: it does not fit the type."""


def _literal(value: object, type_: object) -> str:
    """The Rust expression of a scenario value of the scalar type ``type_``."""
    assert isinstance(type_, ScalarType)
    if type_.category is TypeCategory.BOOL:
        return "true" if value is True else "false"
    if type_.category is TypeCategory.FLOATING:
        bits = 32 if type_.c_name == "float" else 64
        too_big = isinstance(value, float) and math.isfinite(value) and abs(value) > _FLOAT_MAX
        if bits == 32 and too_big:
            raise _Unplayable(f"{value!r} does not fit a float")
        return _float(value, bits)
    number = _integer(value)
    assert number is not None
    low, high = _integer_range(type_) or (0, 0)
    if not low <= number <= high:
        raise _Unplayable(f"{number} does not fit a {type_.c_name}")
    return str(number)


class _Program:
    """The Rust program: a function for each scenario."""

    def __init__(
        self, plan_name: str, plan: ModulePlan, found: dict[str, Target], plan_index: object
    ) -> None:
        self.crate = plan_name
        self.found = found
        self.index = plan_index
        self.names = build_names(plan)
        self.enums = scenarios.enum_types(plan)
        self.structs = scenarios.struct_types(plan)
        self.classes = {
            item.c_type: item
            for header in plan.headers
            for item in header.items
            if isinstance(item, ClassPlan)
        }
        self.scenarios: list[tuple[str, list[str]]] = []
        self.kinds: dict[str, str] = {}
        """The C type of the class of each variable."""

        self.parents: dict[str, list[str]] = {}
        """The variables that a borrowed one comes from: it is closed with them."""

    def scenario(self, scenario: dict[str, object]) -> None:
        lines: list[str] = []
        variables: dict[str, str] = {}
        self.kinds = {}
        self.parents = {}
        closed: set[str] = set()
        steps = scenario["steps"]
        assert isinstance(steps, list)
        for number, step in enumerate(steps, start=1):
            self.step(number, step, lines, variables, closed)
        self.scenarios.append((str(scenario["name"]), lines))

    def step(
        self,
        number: int,
        step: dict[str, object],
        lines: list[str],
        variables: dict[str, str],
        closed: set[str],
    ) -> None:
        if "close" in step:
            name = str(step["close"])
            if name not in closed:
                lines.append(f"drop({variables[name]});")
                closed.add(name)
            return  # a second close does not exist in Rust: the object is gone
        if "derive" in step:
            raise NotImplementedError("the Rust bindings do not derive classes yet")
        error = step.get("error")
        target = self.found[str(step["c"])]
        call = target.call
        args = step.get("args", [])
        assert isinstance(args, list)
        used = [str(arg["ref"]) for arg in args if isinstance(arg, dict) and "ref" in arg]
        owner = str(step["call"]).split(".")[0] if "call" in step else ""
        if error == "closed":
            if self.gone(owner, closed) or any(self.gone(name, closed) for name in used):
                return  # a closed object cannot be used in a program that compiles
            lines.append(
                f'return Err(({number}, "nothing was closed: the call is possible".into()));'
            )
            return
        try:
            expression = self.expression(step, target, args, variables)
        except _Unplayable as problem:
            if error == "range":
                return  # the type of the parameter cannot take the value: it does not compile
            lines.append(f"return Err(({number}, {_string(str(problem))}.to_string()));")
            return
        if error == "range":
            lines.append(
                f'return Err(({number}, "no argument is out of range: the call works".into()));'
            )
            return
        if error == "length":
            lines.append(
                f'return Err(({number}, "no array has a wrong length: the call works".into()));'
            )
            return
        if error is not None:
            kind = f"{self.crate}::ErrorKind::{_KINDS[str(error)]}"
            message = step.get("message")
            text = "None" if message is None else f"Some({_string(str(message))})"
            lines.append(f"fails({number}, {expression}, {kind}, {text})?;")
            return
        self.after_call(step, target, args, closed)
        if "new" in step:
            variable = _identifier(str(step["as"]))
            variables[str(step["as"])] = variable
            self.kinds[str(step["as"])] = target.class_type or ""
            lines.append(f"let mut {variable} = ok({number}, {expression})?;")
            return
        if call.result is None:
            lines.append(f"ok({number}, {expression})?;")
            return
        if isinstance(call.result.type, ClassRef):
            self.object_result(number, step, call, expression, lines, variables)
            return
        lines.append(f"let value = ok({number}, {expression})?;")
        if "expect" in step:
            lines.extend(self.compare(number, step, call))

    def gone(self, name: str, closed: set[str]) -> bool:
        """The object of a variable was closed, or it is borrowed from one that was."""
        return name in closed or any(
            self.gone(parent, closed) for parent in self.parents.get(name, [])
        )

    def after_call(
        self, step: dict[str, object], target: Target, args: list[object], closed: set[str]
    ) -> None:
        """The objects that the call takes away are gone (closed) from now on."""
        for value, spec in zip(args, target.call.params, strict=True):
            if isinstance(value, dict) and "ref" in value and self.transfers(spec):
                closed.add(str(value["ref"]))

    @staticmethod
    def transfers(spec: object) -> bool:
        words: frozenset[str] = getattr(spec, "words", frozenset())
        ref = getattr(spec, "type", None)
        return "transfer" in words or (isinstance(ref, ClassRef) and ref.form is ClassForm.UNIQUE)

    def object_result(
        self,
        number: int,
        step: dict[str, object],
        call: CallablePlan,
        expression: str,
        lines: list[str],
        variables: dict[str, str],
    ) -> None:
        """An object that a call gives: a variable, or a NULL that the scenario expects."""
        assert call.result is not None
        ref = call.result.type
        assert isinstance(ref, ClassRef)
        nullable = ref.form not in (ClassForm.VALUE, ClassForm.REFERENCE, ClassForm.CONST_REFERENCE)
        expected = step.get("expect")
        if isinstance(expected, dict) and expected.get("null") is True:
            lines.append(f"let value = ok({number}, {expression})?;")
            lines.append("if value.is_some() {")
            lines.append(f'    return Err(({number}, "expected NULL, got an object".into()));')
            lines.append("}")
            return
        if "as" not in step:
            lines.append(f"ok({number}, {expression})?;")
            return
        variable = _identifier(str(step["as"]))
        variables[str(step["as"])] = variable
        assert call.result.cls is not None
        self.kinds[str(step["as"])] = call.result.cls.c_type
        if is_borrowed(call.result, ref):
            owners = [str(step["call"]).split(".")[0]] if call.kind is CallableKind.METHOD else []
            for argument in step.get("args", []):  # type: ignore[attr-defined]
                if isinstance(argument, dict) and "ref" in argument:
                    owners.append(str(argument["ref"]))
            self.parents[str(step["as"])] = owners
        if nullable:
            lines.append(f"let mut {variable} = match ok({number}, {expression})? {{")
            lines.append("    Some(object) => object,")
            lines.append(
                f'    None => return Err(({number}, "an object was expected: NULL".into())),'
            )
            lines.append("};")
        else:
            lines.append(f"let mut {variable} = ok({number}, {expression})?;")

    def expression(
        self, step: dict[str, object], target: Target, args: list[object], variables: dict[str, str]
    ) -> str:
        call = target.call
        rendered = []
        for value, spec in zip(args, call.params, strict=True):
            problem = scenarios._kind_problem(
                value, spec.type, self.index, self.owners(), result=False
            )  # type: ignore[arg-type]
            if problem is not None:
                raise _Unplayable(problem)
            nullable = "nullable" in spec.words
            if isinstance(spec.type, ClassRef):
                rendered.append(self.object_argument(value, spec, nullable, variables))
            else:
                rendered.append(self.render(value, spec.type, spec_enum=spec, nullable=nullable))
        arguments = ", ".join(rendered)
        if call.kind is CallableKind.METHOD:
            name = str(step["call"]).split(".")[0]
            receiver = self.convert(
                variables[name],
                self.kinds[name],
                target.class_type or "",
                mutable=not call.is_const,
            )
            return f"{receiver}.{target.path}({arguments})"
        return f"{target.path}({arguments})"

    def owners(self) -> dict[str, ClassPlan | None]:
        """The class of each variable, as the checks of the scenarios want it."""
        return {name: self.classes.get(kind) for name, kind in self.kinds.items()}

    def object_argument(
        self, value: object, spec: object, nullable: bool, variables: dict[str, str]
    ) -> str:
        """An object that a function takes: a reference to the variable (or the variable, if the
        call takes it away) seen as the class of the parameter."""
        table = value if isinstance(value, dict) else {}
        if table.get("null") is True:
            return "None"
        name = str(table["ref"])
        parameter = getattr(spec, "cls", None)
        assert parameter is not None
        ref = getattr(spec, "type", None)
        assert isinstance(ref, ClassRef)
        if self.transfers(spec):
            owned = self.convert_owned(variables[name], self.kinds[name], parameter.c_type)
            return f"Some({owned})" if nullable else owned
        constant = ref.form in (
            ClassForm.VALUE,
            ClassForm.CONST_REFERENCE,
            ClassForm.CONST_POINTER,
        )
        view = self.convert(
            variables[name], self.kinds[name], parameter.c_type, mutable=not constant
        )
        borrowed = (
            view
            if "." in view
            else (f"&{variables[name]}" if constant else f"&mut {variables[name]}")
        )
        return f"Some({borrowed})" if nullable else borrowed

    def chain(self, source: str, target: str) -> list[tuple[int, str]] | None:
        """The classes from ``source`` down to ``target`` by bases (``None``: not related)."""
        if source == target:
            return []
        plan = self.classes[source]
        for position, base in enumerate(plan.bases):
            rest = self.chain(base.c_type, target)
            if rest is not None:
                return [(position, base.c_type), *rest]
        return None

    def convert(self, variable: str, source: str, target: str, *, mutable: bool) -> str:
        """The expression that sees the object of ``variable`` (a class ``source``) as a
        ``target``: the first base is reached by deref, the others by ``as_<base>``."""
        found = self.chain(source, target)
        assert found is not None, (source, target)
        expression = variable
        for position, base in found:
            if position != 0:
                word = snake(self.classes[base].model.name)
                expression = f"{expression}.as_{word}{'_mut' if mutable else ''}()"
        return expression

    def convert_owned(self, variable: str, source: str, target: str) -> str:
        """The object of ``variable`` owned as a ``target`` (C++ destroys it through it)."""
        found = self.chain(source, target)
        assert found is not None, (source, target)
        expression = variable
        for position, base in found:
            word = "into_base" if position == 0 else f"into_{snake(self.classes[base].model.name)}"
            expression = f"{expression}.{word}()"
        return expression

    def path(self, path: str) -> str:
        """A path of the crate, from outside it."""
        return path.replace("crate::", f"{self.crate}::", 1)

    def render(
        self, value: object, type_: object, *, spec_enum: object = None, nullable: bool = False
    ) -> str:
        """The Rust expression of a scenario value of the type ``type_``."""
        if isinstance(type_, ScalarType):
            return _literal(value, type_)
        if isinstance(type_, StringType):
            if isinstance(value, dict) and value.get("null") is True:
                return "None"
            text = _string(str(value))
            return f"Some({text})" if nullable else text
        table = value if isinstance(value, dict) else {}
        if isinstance(type_, EnumRef):
            enum = self.enums[str(table["enum"])]
            return (
                f"{self.path(self.names.enums[enum.c_type])}::{upper_snake(str(table['member']))}"
            )
        if isinstance(type_, StructRef):
            struct = self.structs[str(table["struct"])]
            fields = []
            for member, name in zip(struct.fields, field_names(struct), strict=True):
                given = table[member.model.name]
                kind = member.model.type
                if member.model.length is not None:
                    assert isinstance(given, list)
                    items = ", ".join(self.render(item, kind) for item in given)
                    fields.append(f"{name}: [{items}]")
                else:
                    fields.append(f"{name}: {self.render(given, kind)}")
            return f"({self.path(self.names.structs[struct.c_type])} {{ {', '.join(fields)} }})"
        raise NotImplementedError(f"the type {getattr(type_, 'cpp_spelling', type_)}")

    def compare(self, number: int, step: dict[str, object], call: CallablePlan) -> list[str]:
        assert call.result is not None
        type_ = call.result.type
        expected = step["expect"]
        problem = scenarios._kind_problem(expected, type_, self.index, {}, result=True)  # type: ignore[arg-type]
        if problem is not None:
            return [
                f"return Err(({number}, {_string('the scenario expects ' + problem)}.to_string()));"
            ]
        if isinstance(type_, StringType):
            literal = self.render(expected, type_, nullable=not type_.sized)
            shown = "value" if type_.sized else "value.as_deref()"
            if not type_.sized and isinstance(expected, str):
                literal = f"Some({_string(expected)})"
            condition = f"{shown} != {literal}"
        elif isinstance(type_, ScalarType):
            literal = _literal(expected, type_)
            if type_.category is TypeCategory.FLOATING:
                approx = step.get("approx")
                if isinstance(expected, float) and math.isnan(expected):
                    condition = "!value.is_nan()"
                elif approx is not None:
                    condition = f"!((value - {literal}).abs() <= {_float(approx, 64)})"
                else:
                    condition = f"value != {literal}"
            else:
                condition = f"value != {literal}"
        else:
            condition = f"value != {self.render(expected, type_)}"
        return [
            f"if {condition} {{",
            f'    return Err(({number}, format!("expected {{}}, got {{:?}}", '
            f"{_string(str(expected))}, value)));",
            "}",
        ]

    def source(self) -> str:
        text = [_PRELUDE.format(crate=self.crate)]
        for position, (_, lines) in enumerate(self.scenarios):
            text.append(f"fn scenario_{position}() -> Result<(), Failure> {{")
            text.extend(f"    {line}" for line in lines)
            text.append("    Ok(())")
            text.append("}")
            text.append("")
        text.append("fn main() {")
        text.append("    let mut failed = false;")
        for position, (name, _) in enumerate(self.scenarios):
            text.append(f"    if let Err((step, message)) = scenario_{position}() {{")
            label = _string(name)
            text.append(
                f'        eprintln!("FAILED {{}}, step {{}}: {{}}", {label}, step, message);'
            )
            text.append("        failed = true;")
            text.append("    }")
        text.append("    if failed {")
        text.append("        std::process::exit(1);")
        text.append("    }")
        text.append(f'    println!("conformance OK (rust): {len(self.scenarios)} scenarios");')
        text.append("}")
        return "\n".join(text) + "\n"


def _string(text: str) -> str:
    """A Rust string literal: what is not printable ASCII is a Unicode escape."""
    out = ['"']
    for char in text:
        code = ord(char)
        if char == '"':
            out.append('\\"')
        elif char == "\\":
            out.append("\\\\")
        elif 0x20 <= code < 0x7F:
            out.append(char)
        else:
            out.append(f"\\u{{{code:x}}}")
    out.append('"')
    return "".join(out)


def _identifier(name: str) -> str:
    return "v_" + re.sub(r"[^A-Za-z0-9_]", "_", name)


def _crate(case: Case, output: Path) -> Path:
    """The directory of the generated crate of ``case`` (generated once per output)."""
    crate_dir = output / "rust-crate"
    if not crate_dir.exists():
        options = dataclasses.replace(case.options(("rust",)), verify=False)
        result = bridgefex.generate(case.headers, options)
        bridgefex.write_files(result.files, crate_dir)
    return crate_dir / "rust" / case.module


def _cargo_program(
    case: Case, library: Path, output: Path, name: str, source: str | Path, command: str
) -> Path:
    """Run ``cargo command`` (``build`` or ``check``) on a crate whose ``main.rs`` is ``source``
    (a text, or a file) and that depends on the crate of ``case``: the path of the executable
    that ``build`` makes. Raises RuntimeError with the messages of cargo if it fails."""
    package = "p_" + re.sub(r"[^A-Za-z0-9_]", "_", name)
    work = output / f"rust-{name}"
    shutil.rmtree(work, ignore_errors=True)
    (work / "src").mkdir(parents=True)
    (work / "Cargo.toml").write_text(
        _CARGO.format(crate=case.module, path=_crate(case, output).as_posix(), name=package),
        encoding="utf-8",
    )
    text = source.read_text(encoding="utf-8") if isinstance(source, Path) else source
    (work / "src" / "main.rs").write_text(text, encoding="utf-8")
    cargo_command = cargo()
    assert cargo_command is not None
    completed = subprocess.run(
        [
            cargo_command,
            command,
            "--offline",
            "--quiet",
            "--manifest-path",
            str(work / "Cargo.toml"),
        ],
        capture_output=True,
        text=True,
        check=False,
        env=environment(case, output, library),
        timeout=900,
    )
    if completed.returncode != 0:
        raise RuntimeError(completed.stdout + completed.stderr)
    suffix = ".exe" if sys.platform == "win32" else ""
    return output / "rust-target" / "debug" / (package + suffix)


def build_program(case: Case, library: Path, output: Path, name: str, source: str | Path) -> Path:
    """The program ``source`` (the text of a ``main.rs``, or a file with one) built against the
    crate of ``case``: the executable. Raises RuntimeError if it does not build."""
    return _cargo_program(case, library, output, name, source, "build")


def check_program(case: Case, library: Path, output: Path, name: str, source: str | Path) -> None:
    """Compile ``source`` against the crate of ``case`` without linking it. Raises RuntimeError
    with the messages of the compiler if it is refused."""
    _cargo_program(case, library, output, name, source, "check")


def build_runner(case: Case, library: Path, output: Path, path: Path) -> Path:
    """The program that plays ``path`` against the crate of ``case``: the executable.
    Raises RuntimeError if it does not build."""
    plan = plan_of(case)
    index = scenarios._Index.of(plan)
    program = _Program(case.module, plan, targets(plan), index)
    for scenario in scenarios.resolve(scenarios.load(path), plan):
        program.scenario(scenario)
    return build_program(case, library, output, f"{path.parent.name}-{path.stem}", program.source())


def environment(case: Case, output: Path, library: Path) -> dict[str, str]:
    environment = {
        **os.environ,
        "CARGO_TARGET_DIR": str(output / "rust-target"),
        "CARGO_NET_OFFLINE": "true",
        "CARGO_TERM_COLOR": "never",
        "RUSTFLAGS": "-D warnings",
    }
    directory = str(library.parent)
    environment[f"{case.module.upper()}_LIB_DIR"] = directory
    variable = {"win32": "PATH", "darwin": "DYLD_LIBRARY_PATH"}.get(sys.platform)
    variable = variable or "LD_LIBRARY_PATH"
    environment[variable] = directory + os.pathsep + environment.get(variable, "")
    return environment


def run(case: Case, library: Path, output: Path, path: Path) -> subprocess.CompletedProcess[str]:
    """Play the scenarios of ``path`` against the Rust bindings of ``case``."""
    try:
        executable = build_runner(case, library, output, path)
    except RuntimeError as error:
        return subprocess.CompletedProcess([], 3, "", str(error))
    return subprocess.run(
        [str(executable)],
        capture_output=True,
        text=True,
        check=False,
        env=environment(case, output, library),
        timeout=600,
    )
