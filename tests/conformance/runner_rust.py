"""Plays the conformance scenarios against the Rust bindings.

Rust has no reflection: the runner cannot find what to call by name, as the runners of C#
and Java do. It writes a Rust program instead, one function for each scenario, that calls the
generated crate as a user's code would, compiles it with the crate and runs it with the library
of the case. The scenarios are checked against the plan first (``scenarios.check``), so what
the program cannot say is what Rust cannot do: a value that does not fit its C type, a length
that the type of an array fixes and an object that was closed are not possible in a program that
compiles, and a scenario that asks for one of them is true (the step is not played) only if the
step really has such a thing.
"""

from __future__ import annotations

import ctypes
import dataclasses
import math
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

import bridgefex
from bridgefex.backends.rust.check import cargo
from bridgefex.backends.rust.module import Target, targets
from bridgefex.model import ScalarType, TypeCategory
from bridgefex.plan import CallableKind, CallablePlan
from tests.conformance import scenarios
from tests.support.cases import Case
from tests.support.plans import plan_of

ENV_REQUIRED = "BRIDGEFEX_REQUIRE_RUST"
"""Set by the CI: a missing cargo is then a failure of the tests that need it, not a skip."""


def available() -> bool:
    return cargo() is not None


def skip_without_rust() -> None:
    """Skip the test if cargo is missing, or fail it if the environment requires it."""
    if available():
        return
    if os.environ.get(ENV_REQUIRED) == "1":
        pytest.fail(f"cargo is required ({ENV_REQUIRED} is set) and it is not installed")
    pytest.skip("needs cargo")


_CARGO = """\
[package]
name = "runner"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
{crate} = {{ path = "{path}" }}

[workspace]
"""

_PRELUDE = """\
// Generated by tests/conformance/runner_rust.py.
#![allow(dead_code, unreachable_code, unused_mut, unused_variables, unused_imports)]

type Failure = (usize, String);

fn ok<T>(step: usize, result: {crate}::Result<T>) -> Result<T, Failure> {{
    result.map_err(|error| {{
        (step, format!("unexpected {{:?}}: {{}}", error.kind(), error.message()))
    }})
}}

fn fails<T>(
    step: usize,
    result: {crate}::Result<T>,
    kind: {crate}::ErrorKind,
    message: Option<&str>,
) -> Result<(), Failure> {{
    match result {{
        Ok(_) => Err((step, format!("expected {{:?}}, and the call succeeded", kind))),
        Err(error) => {{
            if error.kind() != kind {{
                return Err((step, format!("expected {{:?}}, got {{:?}}", kind, error.kind())));
            }}
            match message {{
                Some(text) if !error.message().contains(text) => Err((
                    step,
                    format!("the message {{:?}} does not contain {{:?}}", error.message(), text),
                )),
                _ => Ok(()),
            }}
        }}
    }}
}}
"""

_FLOAT_MAX = 3.4028234663852886e38

_KINDS = {
    "exception": "Exception",
    "unknown_exception": "UnknownException",
    "out_of_memory": "OutOfMemory",
}


def _integer_range(type_: ScalarType) -> tuple[int, int] | None:
    """The values that a C integer type holds on this machine (the runner runs where the library
    was built), or None for a type that is not an integer."""
    if type_.category not in (TypeCategory.SIGNED_INTEGER, TypeCategory.UNSIGNED_INTEGER):
        return None
    name = type_.c_name
    c_types = {
        "signed char": ctypes.c_byte,
        "unsigned char": ctypes.c_ubyte,
        "short": ctypes.c_short,
        "unsigned short": ctypes.c_ushort,
        "int": ctypes.c_int,
        "unsigned int": ctypes.c_uint,
        "long": ctypes.c_long,
        "unsigned long": ctypes.c_ulong,
        "long long": ctypes.c_longlong,
        "unsigned long long": ctypes.c_ulonglong,
        "int8_t": ctypes.c_int8,
        "uint8_t": ctypes.c_uint8,
        "int16_t": ctypes.c_int16,
        "uint16_t": ctypes.c_uint16,
        "int32_t": ctypes.c_int32,
        "uint32_t": ctypes.c_uint32,
        "int64_t": ctypes.c_int64,
        "uint64_t": ctypes.c_uint64,
        "size_t": ctypes.c_size_t,
    }
    bits = ctypes.sizeof(c_types[name]) * 8
    unsigned = name.startswith("unsigned") or name.startswith("uint") or name == "size_t"
    return (0, 2**bits - 1) if unsigned else (-(2 ** (bits - 1)), 2 ** (bits - 1) - 1)


def _integer(value: object) -> int | None:
    if isinstance(value, dict) and set(value) == {"int"}:
        return int(str(value["int"]))
    if isinstance(value, int) and not isinstance(value, bool):
        return value
    return None


def _float(value: object, bits: int) -> str:
    """A floating-point literal of ``bits`` bits."""
    suffix = f"f{bits}"
    number = float(value)  # type: ignore[arg-type]
    if math.isnan(number):
        return f"{suffix}::NAN"
    if math.isinf(number):
        return f"{suffix}::INFINITY" if number > 0 else f"{suffix}::NEG_INFINITY"
    return f"{number!r}_{suffix}"


class _Unplayable(Exception):
    """A value that the scenario gives and the Rust program cannot: it does not fit the type."""


def _literal(value: object, type_: object) -> str:
    """The Rust expression of a scenario value of the scalar type ``type_``."""
    assert isinstance(type_, ScalarType)
    if type_.category is TypeCategory.BOOL:
        return "true" if value is True else "false"
    if type_.category is TypeCategory.FLOATING:
        bits = 32 if type_.c_name == "float" else 64
        too_big = isinstance(value, float) and math.isfinite(value) and abs(value) > _FLOAT_MAX
        if bits == 32 and too_big:
            raise _Unplayable(f"{value!r} does not fit a float")
        return _float(value, bits)
    number = _integer(value)
    assert number is not None
    low, high = _integer_range(type_) or (0, 0)
    if not low <= number <= high:
        raise _Unplayable(f"{number} does not fit a {type_.c_name}")
    return str(number)


class _Program:
    """The Rust program: a function for each scenario."""

    def __init__(self, plan_name: str, found: dict[str, Target], plan_index: object) -> None:
        self.crate = plan_name
        self.found = found
        self.index = plan_index
        self.scenarios: list[tuple[str, list[str]]] = []

    def scenario(self, scenario: dict[str, object]) -> None:
        lines: list[str] = []
        variables: dict[str, str] = {}
        closed: set[str] = set()
        steps = scenario["steps"]
        assert isinstance(steps, list)
        for number, step in enumerate(steps, start=1):
            self.step(number, step, lines, variables, closed)
        self.scenarios.append((str(scenario["name"]), lines))

    def step(
        self,
        number: int,
        step: dict[str, object],
        lines: list[str],
        variables: dict[str, str],
        closed: set[str],
    ) -> None:
        if "close" in step:
            name = str(step["close"])
            if name not in closed:
                lines.append(f"drop({variables[name]});")
                closed.add(name)
            return  # a second close does not exist in Rust: the object is gone
        if "derive" in step:
            raise NotImplementedError("the Rust bindings do not derive classes yet")
        error = step.get("error")
        target = self.found[str(step["c"])]
        call = target.call
        args = step.get("args", [])
        assert isinstance(args, list)
        used = [str(arg["ref"]) for arg in args if isinstance(arg, dict) and "ref" in arg]
        owner = str(step["call"]).split(".")[0] if "call" in step else ""
        if error == "closed":
            if owner in closed or any(name in closed for name in used):
                return  # a closed object cannot be used in a program that compiles
            lines.append(
                f'return Err(({number}, "nothing was closed: the call is possible".into()));'
            )
            return
        try:
            expression = self.expression(step, target, args, variables)
        except _Unplayable as problem:
            if error == "range":
                return  # the type of the parameter cannot take the value: it does not compile
            lines.append(f"return Err(({number}, {_string(str(problem))}.to_string()));")
            return
        if error == "range":
            lines.append(
                f'return Err(({number}, "no argument is out of range: the call works".into()));'
            )
            return
        if error == "length":
            lines.append(
                f'return Err(({number}, "no array has a wrong length: the call works".into()));'
            )
            return
        if error is not None:
            kind = f"{self.crate}::ErrorKind::{_KINDS[str(error)]}"
            message = step.get("message")
            text = "None" if message is None else f"Some({_string(str(message))})"
            lines.append(f"fails({number}, {expression}, {kind}, {text})?;")
            return
        if "new" in step:
            variable = _identifier(str(step["as"]))
            variables[str(step["as"])] = variable
            lines.append(f"let mut {variable} = ok({number}, {expression})?;")
            return
        if call.result is None:
            lines.append(f"ok({number}, {expression})?;")
            return
        lines.append(f"let value = ok({number}, {expression})?;")
        if "expect" in step:
            lines.extend(self.compare(number, step, call))
        if "as" in step:
            raise NotImplementedError("a result that is an object is not played yet")

    def expression(
        self, step: dict[str, object], target: Target, args: list[object], variables: dict[str, str]
    ) -> str:
        call = target.call
        rendered = []
        for value, spec in zip(args, call.params, strict=True):
            problem = scenarios._kind_problem(value, spec.type, self.index, {}, result=False)  # type: ignore[arg-type]
            if problem is not None:
                raise _Unplayable(problem)
            if isinstance(spec.type, ScalarType):
                rendered.append(_literal(value, spec.type))
            else:
                raise NotImplementedError(f"the argument type {spec.type.cpp_spelling}")
        arguments = ", ".join(rendered)
        if call.kind is CallableKind.METHOD:
            variable = variables[str(step["call"]).split(".")[0]]
            return f"{variable}.{target.path}({arguments})"
        return f"{target.path}({arguments})"

    def compare(self, number: int, step: dict[str, object], call: CallablePlan) -> list[str]:
        assert call.result is not None
        type_ = call.result.type
        expected = step["expect"]
        problem = scenarios._kind_problem(expected, type_, self.index, {}, result=True)  # type: ignore[arg-type]
        if problem is not None:
            return [
                f"return Err(({number}, {_string('the scenario expects ' + problem)}.to_string()));"
            ]
        assert isinstance(type_, ScalarType)
        literal = _literal(expected, type_)
        if type_.category is TypeCategory.FLOATING:
            approx = step.get("approx")
            if isinstance(expected, float) and math.isnan(expected):
                condition = "!value.is_nan()"
            elif approx is not None:
                condition = f"!((value - {literal}).abs() <= {_float(approx, 64)})"
            else:
                condition = f"value != {literal}"
        else:
            condition = f"value != {literal}"
        return [
            f"if {condition} {{",
            f'    return Err(({number}, format!("expected {{}}, got {{:?}}", '
            f"{_string(str(expected))}, value)));",
            "}",
        ]

    def source(self) -> str:
        text = [_PRELUDE.format(crate=self.crate)]
        for position, (_, lines) in enumerate(self.scenarios):
            text.append(f"fn scenario_{position}() -> Result<(), Failure> {{")
            text.extend(f"    {line}" for line in lines)
            text.append("    Ok(())")
            text.append("}")
            text.append("")
        text.append("fn main() {")
        text.append("    let mut failed = false;")
        for position, (name, _) in enumerate(self.scenarios):
            text.append(f"    if let Err((step, message)) = scenario_{position}() {{")
            label = _string(name)
            text.append(
                f'        eprintln!("FAILED {{}}, step {{}}: {{}}", {label}, step, message);'
            )
            text.append("        failed = true;")
            text.append("    }")
        text.append("    if failed {")
        text.append("        std::process::exit(1);")
        text.append("    }")
        text.append(f'    println!("conformance OK (rust): {len(self.scenarios)} scenarios");')
        text.append("}")
        return "\n".join(text) + "\n"


def _string(text: str) -> str:
    """A Rust string literal."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def _identifier(name: str) -> str:
    return "v_" + re.sub(r"[^A-Za-z0-9_]", "_", name)


def build_runner(case: Case, library: Path, output: Path, path: Path) -> Path:
    """The program that plays ``path`` against the crate of ``case``: the executable.
    Raises RuntimeError if it does not build."""
    plan = plan_of(case)
    work = output / f"rust-{path.parent.name}-{path.stem}"
    crate_dir = output / "rust-crate"
    if not crate_dir.exists():
        options = dataclasses.replace(case.options(("rust",)), verify=False)
        result = bridgefex.generate(case.headers, options)
        bridgefex.write_files(result.files, crate_dir)
    index = scenarios._Index.of(plan)
    program = _Program(case.module, targets(plan), index)
    for scenario in scenarios.resolve(scenarios.load(path), plan):
        program.scenario(scenario)
    shutil.rmtree(work, ignore_errors=True)
    (work / "src").mkdir(parents=True)
    crate_path = (crate_dir / "rust" / case.module).as_posix()
    (work / "Cargo.toml").write_text(
        _CARGO.format(crate=case.module, path=crate_path), encoding="utf-8"
    )
    (work / "src" / "main.rs").write_text(program.source(), encoding="utf-8")
    command = cargo()
    assert command is not None
    completed = subprocess.run(
        [command, "build", "--offline", "--quiet", "--manifest-path", str(work / "Cargo.toml")],
        capture_output=True,
        text=True,
        check=False,
        env=_environment(case, output, library),
        timeout=900,
    )
    if completed.returncode != 0:
        raise RuntimeError(completed.stdout + completed.stderr)
    name = "runner.exe" if sys.platform == "win32" else "runner"
    return output / "rust-target" / "debug" / name


def _environment(case: Case, output: Path, library: Path) -> dict[str, str]:
    environment = {
        **os.environ,
        "CARGO_TARGET_DIR": str(output / "rust-target"),
        "CARGO_NET_OFFLINE": "true",
        "CARGO_TERM_COLOR": "never",
        "RUSTFLAGS": "-D warnings",
    }
    directory = str(library.parent)
    environment[f"{case.module.upper()}_LIB_DIR"] = directory
    variable = {"win32": "PATH", "darwin": "DYLD_LIBRARY_PATH"}.get(sys.platform)
    variable = variable or "LD_LIBRARY_PATH"
    environment[variable] = directory + os.pathsep + environment.get(variable, "")
    return environment


def run(case: Case, library: Path, output: Path, path: Path) -> subprocess.CompletedProcess[str]:
    """Play the scenarios of ``path`` against the Rust bindings of ``case``."""
    try:
        executable = build_runner(case, library, output, path)
    except RuntimeError as error:
        return subprocess.CompletedProcess([], 3, "", str(error))
    return subprocess.run(
        [str(executable)],
        capture_output=True,
        text=True,
        check=False,
        env=_environment(case, output, library),
        timeout=600,
    )
